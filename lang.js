function setLang(lang) {
  localStorage.setItem("user_lang", lang);
  applyLang(lang);
}

function applyLang(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (i18n[key] && i18n[key][lang]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = i18n[key][lang];
      } else {
        el.innerHTML = i18n[key][lang];
      }
    }
  });

  const dropdownText = document.getElementById("langDropdownText");
  if (dropdownText) {
    if (lang === "en") {
      dropdownText.innerText = " EN";
    } else if (lang === "zh") {
      dropdownText.innerText = " ZH";
    } else {
      dropdownText.innerText = " ID";
    }
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("user_lang") || "id";
  applyLang(savedLang);
});
